import AppKit
import SwiftUI

final class AppDelegate: NSObject, NSApplicationDelegate {
    static var shared: AppDelegate?

    let store = Store()
    private lazy var dock = DockManager(store: store)
    private var statusItem: NSStatusItem?
    private var settingsWindow: NSWindow?

    private var didFinish = false
    private var pendingURLGroupID: UUID?
    private var stubGroupID: UUID?
    private var showingPanel = false
    private var lastPanelShow: TimeInterval = 0

    // MARK: - Launch

    func applicationWillFinishLaunching(_ notification: Notification) {
        // 'GURL' / '----' constants, kept numeric to avoid a Carbon dependency.
        // Kept for compatibility with stubs generated by older builds.
        NSAppleEventManager.shared().setEventHandler(
            self,
            andSelector: #selector(handleGetURL(_:reply:)),
            forEventClass: AEEventClass(0x4755524c),
            andEventID: AEEventID(0x4755524c)
        )
    }

    func applicationDidFinishLaunching(_ notification: Notification) {
        AppDelegate.shared = self
        NSApp.setActivationPolicy(.accessory)
        didFinish = true

        if LaunchMode.isStub {
            guard let id = LaunchMode.stubGroupID else {
                NSApp.terminate(nil)
                return
            }
            stubGroupID = id
            // Defer one runloop turn: activating from inside didFinishLaunching
            // is too early and AppKit silently refuses it.
            DispatchQueue.main.async { self.showStubPanel() }
            return
        }

        setMenuBarVisible(MenuBarPreference.isVisible)

        if let id = pendingURLGroupID {
            // Cold-launched by a legacy stub via dockgroup://.
            pendingURLGroupID = nil
            _ = PanelController.shared.show(groupId: id, store: store, resident: true)
        } else {
            openSettingsWindow()
        }
    }

    /// Reopen events are only relevant while a stub is still alive (the
    /// optional keep-alive preference). With the default "exit on close"
    /// behaviour every Dock click starts a fresh, short-lived process.
    func applicationShouldHandleReopen(_ sender: NSApplication, hasVisibleWindows flag: Bool) -> Bool {
        if LaunchMode.isStub {
            showStubPanel()
            return false
        }
        openSettingsWindow()
        return true
    }

    func applicationDidBecomeActive(_ notification: Notification) {
        guard LaunchMode.isStub, !PanelController.shared.isVisible else { return }
        showStubPanel()
    }

    func applicationShouldTerminateAfterLastWindowClosed(_ sender: NSApplication) -> Bool {
        if LaunchMode.isStub { return false }
        // With the menu bar hidden there is no reason to stay resident.
        return !MenuBarPreference.isVisible
    }

    private func showStubPanel() {
        let now = Date().timeIntervalSince1970
        // One Dock click fires both reopen and didBecomeActive; showing twice
        // rebuilds the panel 50 ms apart and produces a visible flicker.
        guard let id = stubGroupID, !showingPanel, now - lastPanelShow > 0.3 else { return }
        lastPanelShow = now
        showingPanel = true
        defer { showingPanel = false }
        let shown = PanelController.shared.show(groupId: id, store: store, resident: true)
        if !shown { NSApp.terminate(nil) }
    }

    @objc private func handleGetURL(_ event: NSAppleEventDescriptor, reply: NSAppleEventDescriptor) {
        guard let raw = event.paramDescriptor(forKeyword: AEKeyword(0x2d2d2d2d))?.stringValue,
              let components = URLComponents(string: raw),
              components.scheme == "dockgroup",
              let idValue = components.queryItems?.first(where: { $0.name == "id" })?.value,
              let id = UUID(uuidString: idValue) else { return }
        if !didFinish {
            pendingURLGroupID = id
            return
        }
        DispatchQueue.main.async {
            _ = PanelController.shared.show(groupId: id, store: self.store, resident: true)
        }
    }

    // MARK: - Menu bar (optional)

    func setMenuBarVisible(_ visible: Bool) {
        if visible {
            if statusItem == nil {
                let item = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
                item.button?.image = NSImage(systemSymbolName: "square.grid.2x2.fill",
                                             accessibilityDescription: "DockGroup")
                item.button?.toolTip = "DockGroup"
                statusItem = item
            }
            rebuildMenu()
        } else if let item = statusItem {
            NSStatusBar.system.removeStatusItem(item)
            statusItem = nil
        }
    }

    func rebuildMenu() {
        guard statusItem != nil else { return }
        let menu = NSMenu()
        menu.autoenablesItems = false

        if store.config.groups.isEmpty {
            let empty = NSMenuItem(title: "还没有组", action: nil, keyEquivalent: "")
            empty.isEnabled = false
            menu.addItem(empty)
        } else {
            for group in store.config.groups {
                let entry = NSMenuItem(title: group.name,
                                       action: #selector(openGroupMenu(_:)),
                                       keyEquivalent: "")
                entry.target = self
                entry.representedObject = group.id
                menu.addItem(entry)
            }
        }

        menu.addItem(.separator())
        addMenuItem(menu, "设置…", #selector(openSettingsAction(_:)), ",")
        menu.addItem(.separator())
        addMenuItem(menu, "同步到 Dock…", #selector(syncDockAction(_:)), "")
        addMenuItem(menu, "从 Dock 移除所有组", #selector(removeDockAction(_:)), "")
        addMenuItem(menu, "恢复 Dock 备份", #selector(restoreDockAction(_:)), "")
        menu.addItem(.separator())
        addMenuItem(menu, "退出 DockGroup", #selector(quitAction(_:)), "q")
        statusItem?.menu = menu
    }

    private func addMenuItem(_ menu: NSMenu, _ title: String, _ action: Selector, _ key: String) {
        let item = NSMenuItem(title: title, action: action, keyEquivalent: key)
        item.target = self
        menu.addItem(item)
    }

    @objc private func openGroupMenu(_ sender: NSMenuItem) {
        guard let id = sender.representedObject as? UUID else { return }
        _ = PanelController.shared.show(groupId: id, store: store, resident: false)
    }

    // MARK: - Windows

    func openSettingsWindow() {
        if LaunchMode.isStub {
            // The panel process has no settings UI of its own; hand off to the host
            // and exit so it cannot pop back up when focus returns.
            if let url = LaunchMode.hostAppURL {
                NSWorkspace.shared.open(url)
            }
            PanelController.shared.close(forceExit: true)
            return
        }

        if settingsWindow == nil {
            let hosting = NSHostingController(rootView: SettingsView(store: store))
            let window = NSWindow(contentRect: NSRect(x: 0, y: 0, width: 780, height: 580),
                                  styleMask: [.titled, .closable, .miniaturizable, .resizable],
                                  backing: .buffered, defer: false)
            window.title = "DockGroup 设置"
            window.contentViewController = hosting
            window.center()
            window.isReleasedWhenClosed = false
            settingsWindow = window
        }
        NSApp.activate(ignoringOtherApps: true)
        settingsWindow?.makeKeyAndOrderFront(nil)
        rebuildMenu()
    }

    @objc private func openSettingsAction(_ sender: Any?) {
        openSettingsWindow()
    }

    @objc private func syncDockAction(_ sender: Any?) {
        let alert = NSAlert()
        alert.messageText = "同步到 Dock？"
        alert.informativeText = "先备份 com.apple.dock，为每个组生成一个占位 app 放入 Dock 左侧应用区，然后重启 Dock。原有图标不会丢失。"
        alert.addButton(withTitle: "同步")
        alert.addButton(withTitle: "取消")
        NSApp.activate(ignoringOtherApps: true)
        guard alert.runModal() == .alertFirstButtonReturn else { return }
        SettingsState.shared.status = dock.syncToDock()
        rebuildMenu()
        openSettingsWindow()
    }

    @objc private func removeDockAction(_ sender: Any?) {
        SettingsState.shared.status = dock.removeFromDock()
        rebuildMenu()
    }

    @objc private func restoreDockAction(_ sender: Any?) {
        SettingsState.shared.status = dock.restoreLastBackup()
        rebuildMenu()
    }

    @objc private func quitAction(_ sender: Any?) {
        NSApp.terminate(nil)
    }
}
